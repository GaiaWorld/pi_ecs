//! 世界数据快照的归属；不包含系统或调度对象。
/// 独立保存游戏身份、原型与登记资源；不包含真实渲染数据。
/// 不要求 Clone 或序列化；完整恢复由 schedule::recovery 协调。
/// 身份计数/代际/free 链原样保存，引用及容器使用非活动历史表示，不持源 World 活动指针。
/// 可重复恢复到原 World 或兼容登记的空 World，安装时绑定目标，不额外增减保存计数。
/// 通知只保存已发布逻辑记录：按各流序号顺序的头、对应 Removed 历史旧值及其节点/引用责任，
/// 同时保存 first/end、按系统/参数稳定身份关联的订阅游标，以及 None/已创建空流的区别。
/// 不保存队列 capacity/head、环形分段、地址或物理槽；不为捕获调用 make_contiguous。
/// 捕获遵循整体静止点协议，不捕获未完成联合追加或活动 OwningPtr；历史值不操作运行计数。
/// 非活动准备阶段按逻辑顺序重建合法后端队列，保留原序号、tick、游标和空流进度，允许物理布局不同。
/// Removed 头/值一一对应，全部准备成功后才参与整体安装激活，不向运行态暴露半恢复流。
/// 恢复不是普通追加，不重新分配通知序号/tick、不补发通知、不按重新订阅规则跳至流尾。
/// 准备失败清理非活动历史责任且不替换当前 World；安装后失败遵循整体停止规则，不承诺回滚。
